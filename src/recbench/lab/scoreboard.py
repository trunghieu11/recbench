"""The lab's scoreboard: where each method started (the laptop baseline) and what the experiments changed.

    python -m recbench.lab scoreboard            # reports/lab/scoreboard.md
    python -m recbench.lab scoreboard --docs     # also docs/generated/lab/scoreboard.md and one fragment per lab

For each method and dataset it shows the baseline's test NDCG@10 and, when experiments exist, the experiment with the
best *validation* score (never the best test score, which would be luck as much as skill), with its paired difference
to the baseline and the verdict. MostPopular is the floor to beat. When the bake-off's quick-tier results have been
fetched from the box, they are shown for reference only: other hardware and item caps, so they are not paired.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from recbench.compare import BASELINE, Missing, Ref, compare_side, load_side, promotion
from recbench.lab import experiments as ex
from recbench.paths import reports_dir, use_workspace

MARK = {"better": "▲", "worse": "▼", "no clear difference": "="}
HEADER = "<!-- generated by recbench.lab.scoreboard; do not edit -->\n\n"
LEGEND = ("▲ better (the 95% interval of the paired test difference is above 0), ▼ worse (below 0), = no clear difference. "
          "An experiment is chosen per dataset by its validation score.\n")


def _experiment_labels(method: str, tier: str) -> list[str]:
    from recbench.tuning.job import tuning_dir

    labels = [label for label in ex.load_experiments(method) if label != BASELINE]
    for path in sorted(tuning_dir().glob(f"{tier}/*/{method}@*.json")):
        label = path.stem.split("@", 1)[1]
        if label not in labels:
            labels.append(label)
    return labels


def _side(ref: Ref, dataset: str, tier: str):
    """(the loaded side, "") or (None, a short status such as "not run", "running" or "over_budget")."""
    from recbench.tuning.job import read_summary

    try:
        return load_side(ref, dataset, workspace="lab", tier=tier), ""
    except Missing:
        status = (read_summary(tier, dataset, ref.method, label=ref.label) or {}).get("status")
        return None, {None: "not run", "pending": "not run", "finished": "run missing"}.get(status, status)


def _num(value: Any) -> str:
    return "–" if value is None or value != value else f"{float(value):.4f}"


def _mean_ci(values: np.ndarray) -> tuple[float, float, float]:
    from recbench.evaluation import bootstrap_ci

    values = values[~np.isnan(values)]
    low, high = bootstrap_ci(values)
    return float(values.mean()), low, high


def _settings(params: dict[str, Any]) -> str:
    def short(v: Any) -> str:
        if isinstance(v, float):
            return f"{v:.3g}"
        return "null" if v is None else str(v)

    return ", ".join(f"{k}={short(v)}" for k, v in sorted(params.items())) or "defaults"


def _seconds(value: float | None) -> str:
    if value is None or value != value:
        return "–"
    return f"{value:.1f} s" if value < 60 else f"{value / 60:.1f} min" if value < 3600 else f"{value / 3600:.1f} h"


def method_fragment(method: str, datasets: list[str], tier: str, floor: dict[str, float]) -> tuple[str, dict[str, str]]:
    """(the markdown for docs/generated/lab/<method>.md, {dataset: scoreboard cell})."""
    from recbench.tuning.job import read_summary

    base_rows, cells, sides = [], {}, {}
    for dataset in datasets:
        side, status = _side(Ref(method), dataset, tier)
        sides[dataset] = side
        box = (read_summary(tier, dataset, method, workspace="") or {})
        box_value = (box.get("test") or {}).get("ndcg_at_10") if box.get("status") == "finished" else None
        box_text = f"{box_value:.4f}" if box_value is not None else "–"
        floor_text = f"{floor[dataset]:.4f}" if dataset in floor else "–"
        if side is None:
            base_rows.append(f"| {dataset} | {status} | – | – | – | {floor_text} | {box_text} |")
            cells[dataset] = status if status != "not run" else "–"
            continue
        mean, low, high = _mean_ci(side.values["ndcg_at_10"])
        seeds = f" ({side.seeds} seeds)" if side.seeds > 1 else ""
        base_rows.append(f"| {dataset} | {mean:.4f} [{low:.4f}, {high:.4f}]{seeds} | {_num(side.summary.get('best_val'))} | "
                         f"{_settings(side.summary.get('best_params') or {})} | {_seconds(side.metrics.get('train_seconds'))} | {floor_text} | {box_text} |")
        cells[dataset] = f"{mean:.4f}"
    lines = ["**Your starting point: the laptop baseline.** The bake-off's tuning, repeated on this laptop: 10 settings tried on "
             "the validation fold, the best one tested once. Test NDCG@10 with its 95% interval; random methods are averaged over "
             "3 seeds.", "",
             "| Dataset | Test NDCG@10 | Validation | Best settings found | Train time | Floor (MostPopular) | Bake-off (box) |",
             "|---|---|---|---|---|---|---|", *base_rows, ""]

    labels = _experiment_labels(method, tier) if method != ex.REFERENCE else []
    if not labels:
        if method != ex.REFERENCE:
            lines += [f"**Your experiments:** none yet. Define one in `labs/{ex.lab_folders()[method].name}/experiments.yaml`, then "
                      f"`python -m recbench.lab run --method {method} --experiment <label>`.", ""]
        return "\n".join(lines), cells
    exp_rows, best_by_dataset = [], {}
    for label in labels:
        row = [label]
        verdicts = []
        for dataset in datasets:
            other, status = _side(Ref(method, label), dataset, tier)
            if other is None or sides[dataset] is None:
                row.append(status if other is None else "–")
                continue
            result = compare_side(sides[dataset], other)
            verdicts.append(result["verdict"])
            row.append(f"{result['diff']:+.4f} {MARK.get(result['verdict'], '')}")
            val = other.summary.get("best_val")
            if val is not None and (dataset not in best_by_dataset or val > best_by_dataset[dataset][0]):
                best_by_dataset[dataset] = (val, label, result)
        rule = promotion(pd.DataFrame({"verdict": verdicts}), len(datasets)) if verdicts else "not run yet"
        note = ex.load_experiments(method).get(label, {}).get("note", "")
        promoted = " (promoted)" if ex.load_experiments(method).get(label, {}).get("promoted") else ""
        exp_rows.append("| " + " | ".join([f"{row[0]}{promoted}", *row[1:], rule, str(note)]) + " |")
    for dataset, (_, label, result) in best_by_dataset.items():
        cells[dataset] = f"{cells[dataset]} → {result['b']:.4f} {MARK.get(result['verdict'], '')} ({label})"
    lines += ["**Your experiments.** Paired difference to the baseline in test NDCG@10 over the same users.", "",
              "| Experiment | " + " | ".join(datasets) + " | Promotion rule | Note |",
              "|" + "---|" * (len(datasets) + 3), *exp_rows, "", LEGEND]
    return "\n".join(lines), cells


def build(docs_dir: Path | None = None, out_dir: Path | None = None) -> dict[str, str]:
    """Write reports/lab/scoreboard.md (and the docs fragments with docs_dir); returns {name: markdown}."""
    use_workspace("lab")
    datasets = ex.lab_datasets()
    tier = str(ex.lab_benchmark().get("tier", "quick"))
    folders = ex.lab_folders()
    fragments: dict[str, str] = {}
    floor: dict[str, float] = {}
    for dataset in datasets:
        side, _ = _side(Ref(ex.REFERENCE), dataset, tier)
        if side is not None:
            floor[dataset] = float(np.nanmean(side.values["ndcg_at_10"]))
    rows = []
    floor_cells = [f"{floor[d]:.4f}" if d in floor else "–" for d in datasets]
    rows.append(f"| [MostPopular](../dictionary/algorithms/most-popular.md) (the floor) | " + " | ".join(floor_cells) + " | |")
    any_result = bool(floor)
    for week, method in enumerate(folders, start=1):
        text, cells = method_fragment(method, datasets, tier, floor)
        fragments[method] = text
        any_result = any_result or any(cell[:1].isdigit() for cell in cells.values())
        promoted = [label for label, entry in ex.load_experiments(method).items() if entry.get("promoted")]
        rows.append(f"| {week}. [{method}]({folders[method].name}.md) | " + " | ".join(cells.get(d, "–") for d in datasets)
                    + f" | {', '.join(promoted)} |")
    intro = ("Test NDCG@10 of each lab method on the quick tier, tuned on this laptop. A cell reads *baseline → best experiment "
             "verdict (experiment)* once you have experiments. The floor row is MostPopular: a method below it has not learned more "
             "than \"what is popular now\".\n\n")
    table = "\n".join(["| Method | " + " | ".join(datasets) + " | Promoted |", "|" + "---|" * (len(datasets) + 2), *rows])
    fragments["scoreboard"] = intro + table + "\n\n" + LEGEND
    if not any_result:
        fragments["scoreboard"] = ("_No lab results yet._ Compute the baseline with `python -m recbench.lab baseline` (about half "
                                   "a day; it resumes if interrupted), then rebuild with `python -m recbench.lab scoreboard --docs`.\n\n"
                                   + fragments["scoreboard"])
    if docs_dir is not None:
        target = docs_dir / "generated" / "lab"
        target.mkdir(parents=True, exist_ok=True)
        for name, text in fragments.items():
            (target / f"{name}.md").write_text(HEADER + text + ("\n" if not text.endswith("\n") else ""))
    out_dir = out_dir or reports_dir("lab")
    out_dir.mkdir(parents=True, exist_ok=True)
    parts = ["# Lab scoreboard", "", fragments["scoreboard"]]
    for method in folders:
        parts += [f"## {method}", "", fragments[method]]
    (out_dir / "scoreboard.md").write_text("\n".join(parts) + "\n")
    return fragments
